//! 国民健康保険料の 47都道府県＋全国平均 代表料率テーブル
//!
//! - 40歳未満（介護分なし）＝「医療分（基礎分）＋後期高齢者支援金分」の合算値。
//! - 令和8年度（2026年度）から加わった「子ども・子育て支援金分」は全国共通の近似値として
//!   [`KODOMO_RATE_BP`] / [`KODOMO_PER_CAPITA`] で別途加算する（[`crate::nhi`] 参照）。
//! - 東京都は特別区（23区）共通基準の令和8年度料率（医療分 7.51%/47,600円 ＋ 支援金分 2.80%/17,600円）。
//! - その他の道府県は県庁所在地等の代表市（県単位で保険料水準を統一済みの府県は府県標準）を想定した
//!   **概算値**。実際の料率は市区町村・年度ごとに異なるため、正確な額は各自治体の公表値を確認すること。
//! - 料率を更新する場合はこのテーブルの数値だけを書き換えればよい（ロジック側の変更は不要）。

/// 1都道府県分の料率
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NhiRate {
    /// 都道府県名
    pub name: &'static str,
    /// 代表とした市区町村
    pub city: &'static str,
    /// 所得割率（医療分＋支援金分）。1/100 % 単位（1031 = 10.31%）
    pub income_rate_bp: i64,
    /// 均等割額（1人あたり年額・円）
    pub per_capita: i64,
    /// 平等割額（1世帯あたり年額・円）。2方式の自治体は 0
    pub per_household: i64,
}

const fn r(
    name: &'static str,
    city: &'static str,
    income_rate_bp: i64,
    per_capita: i64,
    per_household: i64,
) -> NhiRate {
    NhiRate {
        name,
        city,
        income_rate_bp,
        per_capita,
        per_household,
    }
}

