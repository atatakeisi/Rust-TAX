/// インデックスから料率を取得（範囲外は全国平均）
pub fn get(index: usize) -> &'static NhiRate {
    NHI_TABLE
        .get(index)
        .unwrap_or(&NHI_TABLE[NATIONAL_AVERAGE_INDEX])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_complete() {
        assert_eq!(NHI_TABLE.len(), 48);
        assert_eq!(NHI_TABLE[0].name, "北海道");
        assert_eq!(NHI_TABLE[TOKYO_INDEX].name, "東京都");
        assert_eq!(NHI_TABLE[46].name, "沖縄県");
        assert!(NHI_TABLE[NATIONAL_AVERAGE_INDEX].name.contains("全国平均"));
        let prefs = NHI_TABLE.iter().filter(|p| p.name.ends_with(['都', '道', '府', '県'])).count();
        assert_eq!(prefs, 47);
    }

    #[test]
    fn rates_are_sane() {
        for p in NHI_TABLE.iter() {
            assert!((700..=1_500).contains(&p.income_rate_bp), "{}", p.name);
            assert!((20_000..=80_000).contains(&p.per_capita), "{}", p.name);
            assert!((0..=60_000).contains(&p.per_household), "{}", p.name);
        }
    }

    #[test]
    fn out_of_range_falls_back_to_average() {
        assert_eq!(get(999).name, NHI_TABLE[NATIONAL_AVERAGE_INDEX].name);
    }
}
